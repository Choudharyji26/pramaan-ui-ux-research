const NAME = (n) => (n === "ground" ? "--pm-sys-ground" : `--pm-sys-${n}`);
const lines = () => [
  "/* generated by tools/gen-theme.mjs: change the mapping there, not here */",
  ...DARK.flatMap(([n, v]) => (Array.isArray(v) ? v.map((x) => `${NAME(n)}: ${x};`) : [`${NAME(n)}: var(--pm-ref-${v});`])),
];

// Every marker pair in the file, as { start, end } offsets of the text strictly between the markers.
function regions(text) {
  const out = [];
  let from = 0;
  for (;;) {
    const b = text.indexOf(BEGIN, from);
    if (b < 0) break;
    const e = text.indexOf(END, b);
    if (e < 0) throw new Error("tokens.css: " + BEGIN + " without " + END);
    out.push({ start: b + BEGIN.length, end: e });
    from = e + END.length;
  }
  return out;
}

// Indentation of the marker line that opens a region.
function indentOf(text, region) {
  const lineStart = text.lastIndexOf("\n", region.start - BEGIN.length) + 1;
  return text.slice(lineStart, region.start - BEGIN.length);
}

export function render(text) {
  const rs = regions(text);
  if (rs.length !== 2) throw new Error(`tokens.css: expected 2 pm:dark marker pairs, found ${rs.length}`);
  let out = text;
  for (const r of [...rs].reverse()) {
    const ind = indentOf(text, r);
    const body = lines().map((l) => ind + l).join("\n");
    out = out.slice(0, r.start) + "\n" + body + "\n" + ind + out.slice(r.end);
  }
  return out;
}

// Problems (empty array = ok): marker count, the two blocks equal each other, and equal DARK.
export function checkTheme(text) {
  const problems = [];
  let rs;
  try { rs = regions(text); } catch (e) { return [e.message]; }
  if (rs.length !== 2) return [`expected 2 pm:dark marker pairs in tokens.css, found ${rs.length}`];
  const norm = (r) => text.slice(r.start, r.end).split("\n").map((l) => l.trim()).filter(Boolean).join("\n");
  const [a, b] = rs.map(norm);
  if (a !== b) {
    const al = a.split("\n"), bl = b.split("\n");
    const diff = al.findIndex((l, i) => l !== bl[i]);
    problems.push(`the two dark blocks differ (first difference: "${al[diff] ?? "(missing)"}" vs "${bl[diff] ?? "(missing)"}"); run node tools/gen-theme.mjs`);
  }
  if (a !== lines().join("\n")) problems.push("the dark blocks do not match the mapping in tools/gen-theme.mjs; run node tools/gen-theme.mjs");
  return problems;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = readFileSync(tokensPath, "utf8");
  if (process.argv.includes("--check")) {
    const problems = checkTheme(text);
    if (problems.length) { console.log("FAIL tokens.css dark blocks\n  - " + problems.join("\n  - ")); process.exit(1); }
    console.log("ok   tokens.css dark blocks are identical and match gen-theme.mjs");
  } else {
    const next = render(text);
    if (next === text) console.log("tokens.css already up to date (2 dark blocks, " + DARK.length + " roles)");
    else { writeFileSync(tokensPath, next); console.log("tokens.css rewritten (2 dark blocks, " + DARK.length + " roles)"); }
  }
}
