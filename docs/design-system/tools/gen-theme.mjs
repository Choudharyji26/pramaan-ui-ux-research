// Dark theme generator for docs/design-system/tokens.css.
// The dark --pm-sys-* mapping lives ONCE, in DARK below. This script rewrites both dark blocks in tokens.css
// (`:root[data-theme="dark"]` and the `@media (prefers-color-scheme: dark)` guard) between the marker comments
//   /* pm:dark-begin */ ... /* pm:dark-end */
// so the two can never drift. Idempotent: running it twice changes nothing.
//   node docs/design-system/tools/gen-theme.mjs           rewrite tokens.css
//   node docs/design-system/tools/gen-theme.mjs --check   exit 1 if the blocks differ from each other or from DARK
// check-css.mjs imports `checkTheme` and runs it with the stylesheet gate.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = resolve(here, "..", "tokens.css");
export const BEGIN = "/* pm:dark-begin */";
export const END = "/* pm:dark-end */";

// name -> reference token (a string becomes var(--pm-ref-<name>)) or literal lines ([hex-free rgba twin, oklch]).
